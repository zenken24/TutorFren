// Generates supabase/seed.sql (concepts, practice items, curriculum chunks) from the textbook index.
// Curriculum content only - no personal data. Run: node content/scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const root = new URL("../../", import.meta.url);
const ix = JSON.parse(readFileSync(new URL("content/textbook/index.json", root), "utf8"));
const pages = JSON.parse(readFileSync(new URL("content/textbook/pages.en.json", root), "utf8")).pages;
const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const uuid = (key) => { const h = createHash("md5").update(key).digest("hex"); return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`; };
const bn = (s) => String(s).replace(/\d/g, (d) => "০১২৩৪৫৬৭৮৯"[d]);
const out = ["-- GENERATED by content/scripts/build-seed.mjs. Curriculum data from the NCTB Class 5 Mathematics index.", "begin;"];

const lessonConcept = {};
for (const c of ix.chapters) c.lessons.forEach((l, i) => {
  lessonConcept[l.id] = l.concept_id;
  out.push(`insert into public.concepts (id, chapter, lesson_id, title_en, title_bn, prerequisite_concept_id) values (${q(l.concept_id)}, ${c.number}, ${q(l.id)}, ${q(l.title_en)}, ${q(l.title_bn)}, ${i ? q(c.lessons[i - 1].concept_id) : "null"}) on conflict (id) do update set title_en = excluded.title_en, title_bn = excluded.title_bn;`);
});

// ---- items: arithmetic sub-items whose answer can be computed exactly
const HINTS = {
  "×": [["Break the second number into parts (thousands, hundreds, tens, ones) and multiply each part.", "দ্বিতীয় সংখ্যাটিকে ভেঙে (হাজার, শতক, দশক, একক) প্রতিটি অংশ দিয়ে গুণ করো।"], ["Add the partial products, keeping the place values in line.", "আংশিক গুণফলগুলো স্থানীয় মান মিলিয়ে যোগ করো।"]],
  "÷": [["Look at the first digits of the dividend: how many times does the divisor fit?", "ভাজ্যের প্রথম অঙ্কগুলো দেখো: ভাজক কতবার যায়?"], ["Check with: divisor × quotient + remainder = dividend.", "যাচাই করো: ভাজক × ভাগফল + ভাগশেষ = ভাজ্য।"]],
  "+": [["Line up the place values (and decimal points) before adding.", "যোগ করার আগে স্থানীয় মান (ও দশমিক বিন্দু) মিলিয়ে নাও।"]],
  "-": [["Line up the place values (and decimal points) before subtracting.", "বিয়োগ করার আগে স্থানীয় মান (ও দশমিক বিন্দু) মিলিয়ে নাও।"]],
};
const dec = (s) => (s.split(".")[1] ?? "").length;
const fmt = (x, places) => (places ? x.toFixed(places).replace(/0+$/, "").replace(/\.$/, "") : String(x));
function solve(a, op, b) {
  const A = Number(a), B = Number(b), isInt = Number.isInteger(A) && Number.isInteger(B);
  if (op === "×") return fmt(A * B, dec(a) + dec(b));
  if (op === "+") return fmt(A + B, Math.max(dec(a), dec(b)));
  if (op === "-") return A >= B ? fmt(A - B, Math.max(dec(a), dec(b))) : null;
  if (!B) return null;
  if (isInt) { const r = A % B; return r === 0 ? String(A / B) : `${Math.floor(A / B)} remainder ${r}`; }
  const sc = 10 ** Math.max(dec(a), dec(b)); const v = Math.round(A * sc) / Math.round(B * sc);
  const s = v.toFixed(4); return Math.abs(Number(s) - v) < 1e-9 ? fmt(v, 4) : null;
}
const opLesson = { 1: { "×": "c1-l1", "÷": "c1-l6" }, 5: { "×": "c5-l5", "÷": "c5-l7", "+": "c5-l4", "-": "c5-l4" } };
let nItems = 0; const seen = new Set();
for (const b of ix.blocks) {
  if (b.kind === "task" || b.kind === "let_us_try" || ![1, 5].includes(b.chapter)) continue; // other chapters: OCR of fractions is unreliable
  for (const qq of b.questions) for (const s of qq.sub_items) {
    const m = (s.text_en ?? "").replace(/−/g, "-").match(/^(\d+(?:\.\d+)?)\s*([×÷+\-])\s*(\d+(?:\.\d+)?)$/);
    if (!m) continue;
    const [, a, op, c2] = m; const ans = solve(a, op, c2); if (!ans) continue;
    const lesson = b.lesson_id ?? opLesson[b.chapter]?.[op] ?? `c${b.chapter}-l1`;
    const concept = lessonConcept[lesson]; const key = `${concept}|${a}${op}${c2}`;
    if (seen.has(key)) continue; seen.add(key);
    const digits = (a + c2).replace(/\D/g, "").length; const diff = digits <= 5 ? 1 : digits <= 8 ? 2 : 3;
    const ref = `${b.label_en} p.${qq.printed_page} (${s.label})`;
    const verb = { "×": ["Multiply", "গুণ করো"], "÷": ["Divide", "ভাগ করো"], "+": ["Add", "যোগ করো"], "-": ["Subtract", "বিয়োগ করো"] }[op];
    for (const lang of ["en", "bn"]) {
      const expr = `${a} ${op} ${c2}`; const li = lang === "en" ? 0 : 1;
      const prompt = `${verb[li]}: ${lang === "bn" ? bn(expr) : expr}`;
      const answer = lang === "bn" ? bn(ans).replace("remainder", "ভাগশেষ") : ans;
      out.push(`insert into public.items (id, concept_id, difficulty, language, prompt, answer, hints, source_ref) values (${q(uuid(key + lang))}, ${q(concept)}, ${diff}, ${q(lang)}, ${q(prompt)}, ${q(answer)}, ${q(JSON.stringify(HINTS[op].map((h) => h[li])))}::jsonb, ${q(ref)}) on conflict (id) do nothing;`);
      nItems++;
    }
  }
}

// ---- curriculum chunks from the hand-written page summaries (approved = true; raw OCR is NOT loaded)
let nChunks = 0;
for (const p of pages) {
  if (!p.printed_page || !p.summary_verified) continue;
  const lesson = p.lesson_id ? ix.chapters.flatMap((c) => c.lessons).find((l) => l.id === p.lesson_id) : null;
  const content = [lesson ? `${lesson.title_en}.` : "", p.summary, p.worked_example ? `Worked example: ${p.worked_example}` : ""].filter(Boolean).join(" ");
  out.push(`insert into public.curriculum_chunks (id, content, grade, subject, chapter, lesson_id, concept_id, topic, kind, source_edition, page_ref, pdf_page, language, approved) values (${q(uuid("chunk-en-" + p.pdf_page))}, ${q(content)}, 5, 'mathematics', ${p.chapter}, ${q(p.lesson_id)}, ${q(p.concept_id)}, ${q(lesson?.title_en ?? p.kind)}, ${q(p.kind === "lesson" ? "explanation" : "exercise")}, ${q(ix.book.edition)}, ${p.printed_page}, ${p.pdf_page}, 'en', true) on conflict (id) do update set content = excluded.content;`);
  nChunks++;
}
out.push("commit;");
writeFileSync(new URL("supabase/seed.sql", root), out.join("\n") + "\n");
console.log(`concepts ${Object.keys(lessonConcept).length}, items ${nItems}, chunks ${nChunks}`);
